import { readFileSync, mkdirSync } from "node:fs";
import { chromium } from "playwright";
import { expect, it } from "vitest";
import { AdventureSpec } from "@adventure/spec-v3";
import { addMember, createUserClient, serviceClient, uniqueEmail } from "../db/helpers";
import { fakeOutsideSources } from "@/lib/v3/generation/fake-passes";
import { supabaseV3SourceStore } from "@/lib/v3/generation/deps";
import { validateEditedSpec } from "@/lib/v3/edit/validation";
import { specExport } from "@/lib/v3/spec-transfer";
import { createSpecArchive } from "@/lib/v3/spec-archive";
import { portraitKeys } from "@/lib/v3/media/resolvers";

it.runIf(process.env.RUN_VERSION_LOCAL_TESTS === "1")("imports a ZIP update, publishes it and opens release history through the real UI", async () => {
  const origin = process.env.VERSION_TEST_ORIGIN ?? "http://127.0.0.1:3345";
  const school = "00000000-0000-4000-8000-000000003450";
  const admin = serviceClient();
  const org = await admin.from("organization").upsert({ id: school, name: "Local ZIP version UI test school", slug: "local-zip-version-ui-test" }, { onConflict: "id", ignoreDuplicates: true });
  if (org.error) throw org.error;
  const email = uniqueEmail("zip-version-ui");
  const teacher = await createUserClient(email);
  await admin.auth.admin.updateUserById(teacher.userId, { user_metadata: { full_name: "Alex Tan", name: "Alex Tan" } });
  await addMember(school, teacher.userId, "teacher");
  const spec = AdventureSpec.parse(JSON.parse(readFileSync("fixtures/generated/singapore-1819.json", "utf8")));
  spec.title = "Singapore, 1819: A new harbour";
  for (const moment of spec.definingMoments) moment.rules = moment.rules.filter((rule) => !rule.when || !moment.outcomes.find((o) => o.id === moment.rules.find((r) => r.actId === rule.actId && !r.when)?.outcomeId)?.historical || moment.outcomes.find((o) => o.id === rule.outcomeId)?.historical);
  (spec.authoring ??= {}).stageImages = Object.fromEntries(spec.stages.map((s) => [s.id, { type: "fallback" as const }]));
  spec.authoring.portraitImages = Object.fromEntries(portraitKeys(spec).map((key) => [key, { type: "fallback" as const }]));
  const captured = fakeOutsideSources(spec);
  for (const source of captured.documents) for (const doc of spec.documents.filter((d) => d.real && d.citations?.some((c) => c.sourceId === source.id))) source.pages[0].text += "\n\n" + doc.body;
  const sources = captured.documents.map((d) => ({ id: d.id, title: d.title, text: d.pages.map((p) => p.text).join("\n") }));
  expect(validateEditedSpec(spec, sources).errors).toEqual([]);
  const { data: adventure, error } = await admin.from("adventures_v3").insert({ owner_id: teacher.userId, school_id: school, status: "draft", spec, title: spec.title }).select().single();
  if (error) throw error;
  await supabaseV3SourceStore(() => admin).saveOutside(adventure.id, captured.sources, captured.documents);
  expect((await admin.rpc("publish_adventure_v3", { p_id: adventure.id, p_expected_version: 1, p_expected_published: null, p_publish: true })).data).toBe(true);
  const student = await createUserClient(uniqueEmail("zip-version-student"));
  await addMember(school, student.userId, "student");
  const started = await admin.rpc("start_attempt_v3", { p_adventure_id: adventure.id, p_spec_version: 1, p_student_id: student.userId, p_state: {} });
  expect(started.error).toBeNull();
  expect(started.data?.id).toBeTruthy();
  const bundle = specExport(spec, captured.documents, adventure.id, 1);
  bundle.spec.title = "Singapore, 1819: The harbour debate";
  const archive = await createSpecArchive(bundle, async () => { throw Error("Fixture has no external media"); });
  const output = "output/version-management";
  mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const pageErrors: string[] = [];
  page.on("pageerror", (error) => pageErrors.push(error.message));
  try {
    await page.goto(`${origin}/teacher`);
    await page.locator("main summary:visible").filter({ hasText: "Local dev sign-in (email/password)" }).click();
    await page.locator('main input[name="email"]').fill(email);
    await page.locator('main input[name="password"]').fill("password123!");
    await page.getByRole("button", { name: "Sign in or create account", exact: true }).click();
    await page.getByRole("heading", { name: "Choose your next adventure", exact: true }).waitFor();
    await page.goto(`${origin}/v3/teacher/${adventure.id}?view=editor`);
    await page.getByRole("button", { name: "Import / export", exact: true }).click();
    await page.getByRole("heading", { name: "Import version 2", exact: true }).waitFor();
    await page.screenshot({ path: `${output}/01-import-zip-desktop.png` });
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: `${output}/07-transfer-mobile.png` });
    await page.setViewportSize({ width: 1440, height: 1050 });
    await page.getByLabel("Adventure ZIP or JSON", { exact: true }).setInputFiles({ name: "updated-adventure.zip", mimeType: "application/zip", buffer: Buffer.from(archive) });
    await page.getByRole("button", { name: "Import as new version", exact: true }).click();
    await page.waitForURL(`**/v3/teacher/${adventure.id}?view=editor`, { timeout: 60_000 });
    expect(await page.getByRole("dialog", { name: "Adventure versions", exact: true }).count()).toBe(0);
    const row = async () => (await admin.from("adventures_v3").select("spec_version,published_version,status").eq("id", adventure.id).single()).data;
    expect(await row()).toMatchObject({ spec_version: 2, published_version: 1, status: "published" });
    await page.getByRole("button", { name: "Publish changes", exact: true }).click();
    await expect.poll(row).toMatchObject({ spec_version: 2, published_version: 2 });
    await page.getByRole("link", { name: "Version history", exact: true }).click();
    await page.waitForURL(`**/v3/teacher/${adventure.id}/links`);
    await page.getByRole("heading", { name: "Version history", exact: true }).waitFor();
    await page.screenshot({ path: `${output}/02-history-desktop.png` });
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    const firstVersion = page.getByRole("article").filter({ hasText: "Version 1" });
    await page.context().grantPermissions(["clipboard-read", "clipboard-write"]);
    await firstVersion.getByRole("button", { name: "Copy link", exact: true }).click();
    await firstVersion.getByRole("button", { name: "Copied", exact: true }).waitFor();
    const { data: release } = await admin.from("adventure_publications_v3").select("id").eq("adventure_id", adventure.id).eq("version", 1).single();
    const copiedLink = await page.evaluate(() => navigator.clipboard.readText());
    expect(new URL(copiedLink).pathname).toBe(`/v3/join/${release?.id}`);
    await page.screenshot({ path: `${output}/03-history-mobile.png` });
    expect((await admin.from("adventure_versions_v3").select("version").eq("adventure_id", adventure.id)).data).toHaveLength(2);
    expect((await admin.from("attempts_v3").select("spec_version").eq("id", started.data.id).single()).data?.spec_version).toBe(1);
    await firstVersion.getByRole("link", { name: "View results", exact: true }).click();
    await page.waitForURL(`**/v3/teacher/${adventure.id}/summary?version=1`);
    await page.getByRole("heading", { name: spec.title, exact: true }).waitFor();
    expect(pageErrors).toEqual([]);
  } finally { await browser.close(); }
}, 240_000);
